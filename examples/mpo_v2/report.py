        a(f"- **The max-P(goal) comparison (O2).** HiGHS branch and bound on the exact MILP did not leave the root node "
          f"within the budget (DSGO expects 30-90 minutes at full scale), so O2 is the MILP relaxation's bound plus a "
          f"deterministic LP-rounding incumbent: in-tree P(goal) {pct(mrec.get('obj'))} against GBO's "
          f"{pct(mrec.get('start_p_goal'))}, with the relaxation bound at {pct(mrec.get('dual_bound'))} (gap "
          f"{100 * mrec.get('mip_gap', float('nan')):.0f}%). Even this partial maximizer overfits the tree: its "
          f"out-of-sample P(goal) is below O1's (H5), which is the reason the spec makes it a comparison and never the "
          f"recommendation.")
