def interpretation(R, P):
    L = []
    a = L.append
    oos = R["oos"]
    pol = oos["policies"]
    h = oos["headline_policy"]
    tests = R["hypotheses"]
    att = [x for x in R["attribution"]["switch_off"] if x.get("ok")]
    a("## 10. What the results say")
    a("")
    srt = sorted(att, key=lambda x: x["dp_goal"])
    top = [f"{x['family']} ({pp(x['dp_goal'])} OOS, {pp(x['dp_goal_equal_tail'])} at equal tail"
           + ("; needed a Phase I allowance" if x.get("phase1") else "") + ")" for x in srt[:4]]
    a(f"- **Where the value comes from.** Removing a family costs the most P(goal) for: {', '.join(top)}. "
      f"Families whose removal *helps* (positive dP) are ones the LP over-uses in the tree: "
      f"{', '.join(x['family'] + ' ' + pp(x['dp_goal']) for x in srt if x['dp_goal'] > 0.001) or 'none'}.")
    pc = next((x for x in att if x["family"] == "PACE"), None)
    if pc and pc.get("phase1"):
        names = {"SL3": "H3 six-month coverage", "SL4": "H4 named stress", "SL9": "H9 red-event limit",
                 "SL11": "H11 overcommitment", "SL15": "H15 leaf liquidity"}
        rws = ", ".join(names.get(k, k) for k in pc["phase1"].get("allowances", {})) or "a hard row"
        a(f"- **Pacing is load-bearing for the hard liquidity rows.** Holding every commitment budget at plan makes the "
          f"{rws} infeasible (Phase I allowance u* = {pc['phase1']['u_star']:.4f}); the status quo itself breaches it "
          f"on a few paths (it is not subject to the row). O1 cuts the commitment budgets with the lowest post-horizon "
          f"value per $ (secondaries, real assets, private credit, Capital Solutions), which lowers stressed calls, and "
          f"keeps PE above plan. The {pp(pc['dp_goal'])} of the PACE row therefore mixes the value of the pacing mix "
          f"with the cost of meeting the {rws} some other way at plan pacing.")
