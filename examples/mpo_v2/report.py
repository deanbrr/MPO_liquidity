        a(f"- **The three-mark fusion adds {pp(-f10['dp_goal'])} of P(goal) in the headline book** (replacing fused "
          f"beliefs with group priors: {pp(f10['dp_goal'])}). On the null-information placebo book it adds "
          f"{pp(tests['H7']['placebo_F10_dp_goal'])}, as it should. But O1 still sits "
          f"{pp(tests['H7']['placebo_O1_value_at_equal_tail'])} above the risk-matched line on the placebo book, so most "
          f"of O1's value does not come from belief-versus-bid selection: it comes from levers that do not use the "
          f"marks (the opportunistic-book size, hedge-fund redemptions recycled into lower-cost beta, the pacing mix "
          f"and the liquidity plan). H7 was pre-registered on the premise that value is belief-driven; it fails, and "
          f"that is the finding.")
