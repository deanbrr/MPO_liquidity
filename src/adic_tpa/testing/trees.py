"""The fixture scenario tree (BUILD_SPEC v1.1 §4.5, §3.7, §5.12, §5.13; owner WP-03).

SYNTHETIC – NOT ADIC DATA. ``fixture_tree(branching)`` builds a small pooled tree with breadth-first node order
(root, stage 1, stage 2, ...), equal branch probabilities and its leaves assigned to the worlds in turn (leaf i →
world i mod W), so every world's leaves carry probability 1 and interior nodes pool both worlds, as production trees
do (no node identifies a world before the leaves).

*Unreduced* (default; §5.13 "one path per node"): every leaf holds exactly one pooled path and an interior node
the paths of its subtree; the fixture paths share their prefixes, so a node's coefficients equal each member path's
values exactly and H on this tree must reproduce the simulator's cash path (the 1e-9 identity test). *Reduced*:
each leaf holds three paths whose values differ, and node coefficients are probability-weighted means over members.

Node coefficients are rates only (§3.18 ``NodeCoefficients``), generated by arithmetic from the node's stage,
branch and regime (no random numbers), so the tree is bit-identical on every machine. A branch with an odd index
is a crisis branch; a node's regime is the regime of the branch that created it.
"""

from __future__ import annotations

import math
from collections.abc import Sequence
from typing import Final

import numpy as np

from adic_tpa.contracts.arrays import F64
from adic_tpa.contracts.enums import StressState, WorldId
from adic_tpa.contracts.errors import SchemaError
from adic_tpa.contracts.hashing import array_checksum, content_hash
from adic_tpa.contracts.optimizer import NodeCoefficients
from adic_tpa.contracts.taxonomy import GroupRegistry
from adic_tpa.contracts.units import q_rate
from adic_tpa.contracts.world import Tree, TreeSpec

__all__ = ["fixture_tree", "FIXTURE_TREE_WORLDS", "N_FACILITIES"]

FIXTURE_TREE_WORLDS: Final[tuple[WorldId, ...]] = ("M1", "M6")   # MVP worlds (BUILD-38: no code default elsewhere)
N_FACILITIES: Final = 2                                            # the mini book's revolver and NAV facility
_REDUCED_PATHS_PER_LEAF: Final = 3


def _structure(branching: Sequence[int]) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Breadth-first parent, stage and branch index (position among siblings) arrays."""
    parent, stage, branch = [-1], [0], [0]
    level = [0]
    for s, b in enumerate(branching, start=1):
        nxt = []
        for node in level:
            for k in range(b):
                parent.append(node)
                stage.append(s)
                branch.append(k)
                nxt.append(len(parent) - 1)
        level = nxt
    return np.array(parent, dtype=np.int32), np.array(stage, dtype=np.int8), np.array(branch, dtype=np.int64)


def _members(parent: np.ndarray, is_leaf: np.ndarray, per_leaf: int) -> tuple[np.ndarray, np.ndarray, list[list[int]]]:
    n = parent.size
    leaves = np.flatnonzero(is_leaf)
    members: list[list[int]] = [[] for _ in range(n)]
    for i, leaf in enumerate(leaves):
        paths = list(range(i * per_leaf, (i + 1) * per_leaf))
        node = int(leaf)
        while node >= 0:
            members[node].extend(paths)
            node = int(parent[node])
    ptr = np.zeros(n + 1, dtype=np.int32)
    ptr[1:] = np.cumsum([len(m) for m in members])
    idx = np.array([p for m in members for p in sorted(m)], dtype=np.int32)
    return ptr, idx, members


def _regimes(parent: np.ndarray, branch: np.ndarray) -> np.ndarray:
    crisis = np.zeros(parent.size, dtype=bool)
    for node in range(1, parent.size):
        crisis[node] = branch[node] % 2 == 1
    return crisis


def _coefficients(n: int, stage: np.ndarray, crisis: np.ndarray, members: list[list[int]], per_leaf: int,
                  n_private: int, n_amber: int, period_q: int) -> NodeCoefficients:
    """Rates per node (fan periods compounded from the per-quarter rates over ``period_q`` quarters)."""
    def jitter(path: int, scale: float) -> float:
        return 0.0 if per_leaf == 1 else scale * (((path * 7919) % 11) / 10.0 - 0.5)

    def node_mean(fn: object) -> F64:
        out = np.empty(n)
        for node in range(n):
            vals = [fn(node, path) for path in members[node]]    # type: ignore[operator]
            out[node] = math.fsum(vals) / len(vals)
        return out

    def compound(rate_q: F64) -> F64:
        return (1.0 + rate_q) ** period_q - 1.0

    def intensity(rate_q: F64) -> F64:
        return 1.0 - (1.0 - rate_q) ** period_q

    shape = (n, n_private, 2)
    group_scale = 1.0 + 0.05 * np.arange(n_private)[None, :, None]
    young = np.array([1.0, 0.0])[None, None, :]

    def grid(base_young: float, base_mature: float, crisis_shift: float, scale: float = 1e-3) -> F64:
        nodes = node_mean(lambda node, path: (crisis_shift if crisis[node] else 0.0) + jitter(path, scale))
        base = young * base_young + (1.0 - young) * base_mature
        return np.ascontiguousarray(np.broadcast_to((base * group_scale) + nodes[:, None, None], shape))

    delta = intensity(grid(0.030, 0.055, -0.020))
    qcall = intensity(grid(0.080, 0.050, 0.015))
    ret = compound(grid(0.020, 0.018, -0.060, scale=4e-3))
    bid = np.clip(grid(0.85, 0.90, -0.15), 1e-3, 1.2)
    income = np.ascontiguousarray(np.broadcast_to(np.where(np.arange(n_private)[None, :, None] >= n_private - 2,
                                                           0.020, 0.0), shape)) * period_q
    u_per_nav = np.ascontiguousarray(np.broadcast_to(young * 0.60 + (1.0 - young) * 0.10, shape))
    nav_share = np.ascontiguousarray(np.broadcast_to(young * 0.40 + (1.0 - young) * 0.60, shape))
    call_stress = np.clip(grid(0.42, 0.42, 0.10, scale=0.0), 0.0, 1.0)

    def series(calm: float, crisis_value: float, scale: float = 0.0) -> F64:
        return node_mean(lambda node, path: (crisis_value if crisis[node] else calm) + jitter(path, scale))

    cash_q = q_rate(0.0389)
    eq = series(0.018, -0.12, scale=4e-3)
    return NodeCoefficients(
        delta=delta, qcall=qcall, ret_simple=ret, bid=bid, income=income, u_per_nav=u_per_nav, nav_share=nav_share,
        call_stress_12m=call_stress, lo_ret=compound(eq), hf_ret=compound(0.4 * eq + 0.004),
        vm_per_beta=compound(eq), cash_rate=compound(np.full(n, cash_q)), fac_rate=compound(np.full(n, q_rate(0.0474))),
        draw_rate_q=np.full(n, 0.075 / 4.0) * period_q, tau_lo=np.zeros(n), h_im=series(0.04, 0.10),
        ra_debt_rate=compound(np.full(n, q_rate(0.06))), ra_amort=np.full(n, 0.005) * period_q,
        ra_direct_share=np.full(n, 0.5), tail_prem_rate=np.full(n, 0.0015 / 4.0) * period_q,
        tail_value=series(0.0, 0.05), opp_pnl_rate=series(0.001, -0.004) * period_q, delta_im_rate=series(0.0, 0.002),
        opex_rate=np.full(n, 0.001 / 4.0) * period_q,
        hf_phi=np.ascontiguousarray(np.tile([0.24, 0.45, 0.75, 0.95], (n, 1)) * np.where(crisis, 0.8, 1.0)[:, None]),
        fac_avail=np.ascontiguousarray(np.tile(np.where(crisis, 0.5, 1.0)[:, None], (1, N_FACILITIES))),
        amber_depth=np.ascontiguousarray(np.tile(np.where(crisis, 0.10, 0.25)[:, None], (1, n_amber))))


def fixture_tree(branching: tuple[int, ...] = (2, 2, 2), *, unreduced: bool = True, period_q: int = 1,
                 worlds: tuple[WorldId, ...] = FIXTURE_TREE_WORLDS) -> Tree:
    """A small SYNTHETIC ``Tree`` (§4.5): ``branching[s]`` children per node at stage s + 1, quarterly
    (``period_q = 1``) or semiannual (``period_q = 2``) periods, pooled over ``worlds``.

    ``unreduced`` (default): one path per leaf, prefix-sharing paths, exact node coefficients; otherwise three paths
    per leaf and mean coefficients. Default size (2, 2, 2): 15 nodes, 8 leaves, 4 per world.
    """
    if not branching or any(int(b) < 1 for b in branching):
        raise SchemaError(f"fixture_tree: branching must be positive integers, got {branching}")
    if period_q not in (1, 2):
        raise SchemaError(f"fixture_tree: period_q must be 1 (quarterly) or 2 (semiannual), got {period_q}")
    tax = GroupRegistry.for_version("v2")
    n_private, n_amber = len(tax.private()), len(tax.amber_tier())
    parent, stage, branch = _structure(branching)
    n = parent.size
    is_leaf = np.zeros(n, dtype=bool)
    is_leaf[stage == len(branching)] = True
    leaves = np.flatnonzero(is_leaf)
    w = len(worlds)
    if leaves.size < w:
        raise SchemaError(f"fixture_tree: {leaves.size} leaves cannot cover {w} worlds")
    leaf_world = np.full(n, -1, dtype=np.int8)
    leaf_world[leaves] = np.arange(leaves.size) % w
    counts = np.bincount(leaf_world[leaves], minlength=w)
    p_world = np.zeros((n, w))
    p_world[leaves, leaf_world[leaves]] = 1.0 / counts[leaf_world[leaves]]
    p = np.zeros(n)
    p[leaves] = p_world[leaves].sum(axis=1) / w                     # equal mixture weights over the pooled worlds
    for s in range(len(branching) - 1, -1, -1):                      # parents as exact sums of their children
        nodes = np.flatnonzero(stage == s)
        child_mass = np.bincount(parent[1:], weights=p[1:], minlength=n)
        world_mass = np.stack([np.bincount(parent[1:], weights=p_world[1:, k], minlength=n) for k in range(w)], axis=1)
        p[nodes] = child_mass[nodes]
        p_world[nodes] = world_mass[nodes]
    per_leaf = 1 if unreduced else _REDUCED_PATHS_PER_LEAF
    member_ptr, member_idx, members = _members(parent, is_leaf, per_leaf)
    crisis = _regimes(parent, branch)
    coef = _coefficients(n, stage, crisis, members, per_leaf, n_private, n_amber, period_q)
    features = TreeSpec(worlds=worlds).features
    obs = np.zeros((n, len(features)))
    calm = np.array([0.10, 0.08, 0.30, 0.20, 0.02, 0.035, 0.075, 0.0, 0.045])
    hot = np.array([0.45, 0.70, 0.75, 0.80, -0.20, 0.080, 0.100, 0.0, 0.020])
    obs[:] = np.where(crisis[:, None], hot[None, :len(features)], calm[None, :len(features)])
    obs[:, 4] += 0.01 * stage                                      # cumulative equity return drifts by stage
    spec = TreeSpec(k1=int(branching[0]), k4=int(branching[1]) if len(branching) > 1 else 1,
                    fan_leaves=int(branching[-1]), fan_ends_q=(len(branching) * period_q,),
                    paths_per_world=int(per_leaf * leaves.size // w), worlds=worlds, min_tail_leaves_per_world=0,
                    seed=0)
    arrays = dict(parent=parent, t_end=(stage.astype(np.int16) * period_q).astype(np.int16),
                  period_q=np.where(stage == 0, 0, period_q).astype(np.int8), stage=stage, p=p, p_world=p_world,
                  is_leaf=is_leaf, leaf_world=leaf_world, lr_weight=np.ones(n), member_ptr=member_ptr,
                  member_idx=member_idx, obs_centroid=obs,
                  regime_class=np.where(crisis, StressState.CRISIS, StressState.CALM).astype(np.int8))
    tree_hash = content_hash({"spec": spec, "pooled_worlds": worlds, "coef": coef.checksum(),
                              "arrays": array_checksum(*(arrays[k] for k in sorted(arrays)))})
    tree = Tree(spec=spec, tree_hash=tree_hash, pooled_worlds=tuple(worlds), coef=coef, **arrays)
    tree.validate()
    return tree
