"""Engine I/O contracts (BUILD_SPEC v1.1 §3.8; §1.3 decision timing; §1.4 signs; S-ADR-28/29).

Flows are signed from ADIC's point of view (inflow positive, outflow negative; §1.4) and arrive in [path, group or
unit, flow type] order. Random draws are generated by ``rng.draw_block`` before the engine kernels of a step and
passed in as ``NoiseSlice``; no kernel holds RNG state (§1.7).
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from typing import Final

import numpy as np
from pydantic import model_validator

from adic_tpa.contracts.actions import LensAction
from adic_tpa.contracts.arrays import MAX_BLOCK_PATHS, B, F32, F64, I8, ArrayContainer
from adic_tpa.contracts.enums import Clock, ContractModel, N_FLOW_TYPES
from adic_tpa.contracts.errors import SchemaError
from adic_tpa.contracts.ids import GroupId, UnitId

__all__ = [
    "NoiseRequest", "NoiseSlice", "WorldSlice", "ActionSlice", "FlowSlice", "UnitFinancing", "EngineState",
    "FlowCubeMeta", "FlowCube", "N_RECOURSE_RUNGS",
]

N_RECOURSE_RUNGS: Final = 6   # reserve, p2s, liquid, facility, amber, red (contracts.policy.RECOURSE_RUNGS)


class NoiseRequest(ContractModel):
    source: str                                  # e.g. "priv.fund.idio", "priv.company.ev", "sale.success"
    slots: int                                   # uniforms per (path, month, entity)
    entity_ids: tuple[str, ...] | None           # None -> one stream with entity_key 0
    months: tuple[int, ...]                      # month periods covered

    @model_validator(mode="after")
    def _shape(self) -> NoiseRequest:
        if self.slots < 1:
            raise ValueError("slots must be >= 1")
        if any(m < 0 for m in self.months):
            raise ValueError("month periods are non-negative")
        if self.entity_ids is not None and len(set(self.entity_ids)) != len(self.entity_ids):
            raise ValueError("entity_ids must be unique")
        return self


@dataclass(frozen=True, slots=True)
class NoiseSlice(ArrayContainer):
    requests: tuple[NoiseRequest, ...]
    u: dict[str, F64]                            # u[source]: [P, n_months, n_entities, slots], uniforms in [0, 1)

    def _check_invariants(self, bindings: Mapping[str, int]) -> None:
        for req in self.requests:
            arr = self.u.get(req.source)
            if arr is None:
                raise SchemaError(f"NoiseSlice: no uniforms for source {req.source!r}")
            n_ent = 1 if req.entity_ids is None else len(req.entity_ids)
            if arr.shape[1:] != (len(req.months), n_ent, req.slots):
                raise SchemaError(f"NoiseSlice.u[{req.source!r}] shape {arr.shape} disagrees with its request")


@dataclass(frozen=True, slots=True)
class WorldSlice(ArrayContainer):
    clock: Clock
    t: int
    months: tuple[int, ...]
    factors: F32
    regimes: I8
    stress_post: F32
    vol: F32
    fin_window: I8
    asset_returns: F32
    brent: F32                                   # [P, nm, ...]

    def _bindings(self) -> dict[str, int]:
        return {"NM": len(self.months)}


@dataclass(slots=True)
class ActionSlice(ArrayContainer):
    """Mutable: the simulator fills it from ``Policy.act`` at quarter instant ``t``."""

    t: int
    sell_frac: F32               # [P, U]  fraction of current position sold this quarter (discretionary and planned)
    sell_reason: I8              # [P, U]  SaleReason (reporting label; red status comes from ledger.red_test)
    refi_draw_bn: F32            # [P, U]  cash raised against the unit (REFINANCE)
    add_bn: F32                  # [P, U]  exposure added (ADD; LEVER = ADD + refi_draw on the same unit)
    commit_bn: F32               # [P, G]  new commitments this quarter
    contingent_bn: F32           # [P, G]  contingent-budget deployment
    hf_notice_frac: F32          # [P, L]  share of each HF lot noticed (notice dates only)
    sma_runoff: F32              # [P]     ρ ∈ [0, 1], 1 = reinvest, 0 = run off
    p2s_bn: F32
    beta_add_bn: F32
    tail_notional_bn: F32
    opp_scale: F32
    monetize_frac: F32           # [P]
    fac_draw_bn: F32
    fac_repay_bn: F32            # [P, NF]
    reserve_target: F32          # [P]     HQLA* ÷ W
    recourse_order: I8           # [P, 6]  permutation of the rungs (S-ADR-13; no preemptive rung)
    preemptive_raise_bn: F32     # [P]     executed at quarter start, outside recourse_cover (S-ADR-30)

    @classmethod
    def empty(cls, t: int, n_paths: int, n_units: int, n_groups: int, n_lots: int, n_facilities: int,
              *, recourse_order: tuple[int, ...] = (0, 1, 2, 3, 4, 5), sma_runoff: float = 1.0) -> ActionSlice:
        """A do-nothing slice (zero trades, SaleReason.NONE, the given rung order); policies fill it in place."""
        def z(*shape: int) -> F32:
            return np.zeros(shape, dtype=np.float32)
        order = np.asarray(recourse_order, dtype=np.int8)
        if order.shape != (N_RECOURSE_RUNGS,):
            raise SchemaError(f"recourse_order needs {N_RECOURSE_RUNGS} rungs")
        return cls(
            t=t, sell_frac=z(n_paths, n_units), sell_reason=np.zeros((n_paths, n_units), dtype=np.int8),
            refi_draw_bn=z(n_paths, n_units), add_bn=z(n_paths, n_units), commit_bn=z(n_paths, n_groups),
            contingent_bn=z(n_paths, n_groups), hf_notice_frac=z(n_paths, n_lots),
            sma_runoff=np.full(n_paths, sma_runoff, dtype=np.float32), p2s_bn=z(n_paths), beta_add_bn=z(n_paths),
            tail_notional_bn=z(n_paths), opp_scale=np.ones(n_paths, dtype=np.float32), monetize_frac=z(n_paths),
            fac_draw_bn=z(n_paths, n_facilities), fac_repay_bn=z(n_paths, n_facilities), reserve_target=z(n_paths),
            recourse_order=np.ascontiguousarray(np.broadcast_to(order, (n_paths, N_RECOURSE_RUNGS))),
            preemptive_raise_bn=z(n_paths),
        )


@dataclass(frozen=True, slots=True)
class FlowSlice(ArrayContainer):
    engine_id: str
    clock: Clock
    t: int
    by_group: F32                # [P, G, F]   signed $bn, EXTERNAL counterparty only
    intra: F32                   # [P, G, F]   INTRA_ADIC flows; Σ over groups == 0 (float32-aware tolerance, arrays)
    by_unit: F32 | None          # [P, U_e, F] when keep_units=True
    recourse_unit_ids: tuple[UnitId, ...]   # this engine's recourse-eligible units
    by_recourse_unit: F32        # [P, U_r, F] always emitted
    nav_econ: F32
    nav_rep: F32
    unfunded: F32
    encumbered: F32              # [P, U_e] stocks at period end
    hqla_contrib_bn: F32         # [P]         treasury and public sleeves only


@dataclass(slots=True)
class UnitFinancing(ArrayContainer):
    """Per-unit debt created by REFINANCE/LEVER, owned by the engine that owns the unit (BUILD-24). Mutable."""

    unit_ids: tuple[UnitId, ...]
    instrument_ids: tuple[str, ...]
    balance_bn: F64              # [P, U_f]
    rate_q: F64
    amort_q: F64
    ltv_covenant: F64            # [U_f]  per-quarter cost and amortization; covenant LTV on reported NAV
    breached: B                  # [P, U_f]  forced paydown triggered this quarter


class EngineState:
    """Base class of engine states; subclasses hold numpy arrays mutated in place by ``step`` and
    ``apply_recourse``."""

    unit_ids: tuple[UnitId, ...]
    financing: UnitFinancing | None

    def stocks(self) -> tuple[F32, F32, F32]:
        """``(nav_econ, nav_rep, unfunded)``, each [P, U_e]."""
        raise NotImplementedError


class FlowCubeMeta(ContractModel):
    unit_ids: tuple[UnitId, ...]
    group_of: tuple[GroupId, ...]
    quarters: int = 40
    cube_checksum: str
    action: LensAction | None = None             # set for column flows (Δ vs HOLD on CRN)

    @model_validator(mode="after")
    def _units(self) -> FlowCubeMeta:
        if len(self.unit_ids) != len(self.group_of):
            raise ValueError("group_of needs one group per unit")
        if self.action is not None and not 1 <= len(self.unit_ids) <= 3:
            raise ValueError("column cubes carry only the affected units (1-3)")
        return self


@dataclass(frozen=True, slots=True)
class FlowCube(ArrayContainer):
    meta: FlowCubeMeta
    values: F32                  # [P, Q, U, 18] signed $bn per quarter; at most one 2,000-path block

    def _bindings(self) -> dict[str, int]:
        return {"Q": self.meta.quarters, "U": len(self.meta.unit_ids), "F": N_FLOW_TYPES}

    def _check_invariants(self, bindings: Mapping[str, int]) -> None:
        if self.values.shape[0] > MAX_BLOCK_PATHS:
            raise SchemaError(f"FlowCube holds at most one block of {MAX_BLOCK_PATHS} paths (§1.5, §3.17), "
                              f"got {self.values.shape[0]}")
